// The kit's article builder must keep the bytes the regression tests depend on (Latin-1, NUL,
// bare CR, the O-05 raw head, the malformed O-16 line) and testPost must leave Path, Date and
// an empty Message-ID out. Written by ous-sol in the review of the v0.12.0 bump.
func TestKitFixturesKeepSensitiveBytes(t *testing.T) {
	for _, body := range []string{"caf\xe9 noir, na\xefve, \xe0 la carte", "before\x00after", "col1\rcol2 on one line"} {
		a := testArticle(t, "<sol-byte-oracle@test>", group, "X-Octets: caf\xe9").SetBodyLines(body)
		if !bytes.Equal(a.Body, []byte(body+"\r\n")) || !bytes.Contains(a.Bytes(), []byte("X-Octets: caf\xe9\r\n")) {
			t.Fatalf("transit fixture changed sensitive bytes: %q", a.Bytes())
		}
		p := testPost(t, "<sol-byte-oracle@test>", "fixture", body)
		if !bytes.Equal(p.Body, []byte(body+"\r\n")) || p.Has("Path") || p.Has("Date") {
			t.Fatalf("posting fixture changed sensitive bytes/defaults: %q", p.Bytes())
		}
	}
	if testPost(t, "", "no generated id", "body").Has("Message-ID") {
		t.Fatal("empty posting ID was silently generated by builder")
	}
	mbox := testArticle(t, "<sol-mbox@test>", group).Insert(0, "From nobody Thu Dec  8 12:55:04 2016").Bytes()
	if !bytes.HasPrefix(mbox, []byte("From nobody Thu Dec  8 12:55:04 2016\r\n")) {
		t.Fatalf("malformed mbox line normalized: %q", mbox)
	}
	raw := "Path: e2e-peer!not-for-mail\r\nx-lower:no-space\r\nX-Fold: one\r\n\ttwo\r\nX-Trace: one\r\nX-Trace: two\r\n\r\nline one\r\n.dot line\r\n\r\nlast\r\n"
	a := article.Parse([]byte(raw))
	if string(a.Bytes()) != raw {
		t.Fatal("raw parser changed O05-style header/body")
	}
	want := strings.Replace(raw, "Path: e2e-peer!", "Path: "+pathhost+"!e2e-peer!", 1)
	if string(a.Clone().PrependPath(pathhost).Bytes()) != want {
		t.Fatal("expected Path transformation changed other header bytes")
	}
	if string(bodyArticle(t, "<sol-dots@test>").Body) != "e2e body line 1\r\ne2e body line 2\r\n.leading dot\r\n..two dots\r\n.\r\nlast line\r\n" {
		t.Fatal("feed body fixture no longer matches baseline")
	}
}

// The conformance allowance for O-23 must cover only the final HDR 423 of
// no-current-article; any other failure in that check still fails. Written by ous-sol.
func TestKitAllowOnlyFinalHDR423(t *testing.T) {
	var skip []string
	for _, name := range conformance.Names() {
		if name != "no-current-article" {
			skip = append(skip, name)
		}
	}
	for _, tc := range []struct {
		name, command, reply string
		want                 conformance.Status
	}{
		{"healthy", "", "", conformance.Pass},
		{"O23-only", "HDR Subject", "423 no articles in that range", conformance.Skip},
		{"earlier-ARTICLE-bug", "ARTICLE", "423 no articles in that range", conformance.Fail},
		{"different-HDR-bug", "HDR Subject", "500 broken command", conformance.Fail},
	} {
		t.Run(tc.name, func(t *testing.T) {
			st := fakeserver.NewStore()
			st.AddGroup("empty.test", "empty fixture")
			o := fakeserver.Options{Store: st}
			if tc.command != "" {
				o.Faults.OverrideLine = map[string][]string{tc.command: {tc.reply}}
			}
			srv := fakeserver.New(t, o)
			r, err := conformance.Check(conformance.Options{Addr: srv.Addr(), Skip: skip, Allow: allowedKnownIssues})
			if err != nil {
				t.Fatal(err)
			}
			got := r.ByName()["no-current-article"]
			if got.Status != tc.want {
				t.Fatalf("status=%v detail=%q, want %v", got.Status, got.Detail, tc.want)
			}
			if tc.want == conformance.Skip {
				for _, command := range []string{"ARTICLE", "HEAD", "BODY", "STAT", "NEXT", "LAST", "OVER", "HDR Subject"} {
					if !slices.Contains(srv.Lines(), command) {
						t.Fatalf("allow skipped prior check %q: %q", command, srv.Lines())
					}
				}
			}
		})
	}
}
